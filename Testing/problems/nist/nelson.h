struct nelson_model
{
    template <class T> void operator()(const T* b, T* r) const
    {
        using std::exp;
        using std::log;
        const double* y = nelson_y();
        const double* x_data = nelson_x();
        const double* x2_data = nelson_x2();
        for (int i = 0; i < 128; ++i)
        {
            const T x = T(x_data[i]);
            const T x1 = x;
            const T x2 = T(x2_data[i]);
            r[i] = T(log(y[i])) - (b[0] - b[1]*x1*exp(-b[2]*x2));
        }
    }
};

inline void nelson_residuals(const vector_type& b, vector_type& r)
{
    r.resize(128);
    nelson_model{}(b.data(), r.data());
}

inline api::least_squares_problem nelson_least_squares()
{
    api::least_squares_problem problem;
    problem.num_parameters = 3;
    problem.num_residuals  = 128;
    problem.residuals      = nelson_residuals;
    return problem;
}

