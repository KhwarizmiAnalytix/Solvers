struct gauss3_model
{
    template <class T> void operator()(const T* b, T* r) const
    {
        using std::exp;
        const double* y = gauss3_y();
        const double* x_data = gauss3_x();
        for (int i = 0; i < 250; ++i)
        {
            const T x = T(x_data[i]);
            r[i] = T(y[i]) - (b[0]*exp(-b[1]*x) + b[2]*exp(-(x-b[3])*(x-b[3])/(b[4]*b[4])) + b[5]*exp(-(x-b[6])*(x-b[6])/(b[7]*b[7])));
        }
    }
};

inline void gauss3_residuals(const vector_type& b, vector_type& r)
{
    r.resize(250);
    gauss3_model{}(b.data(), r.data());
}

inline api::least_squares_problem gauss3_least_squares()
{
    api::least_squares_problem problem;
    problem.num_parameters = 8;
    problem.num_residuals  = 250;
    problem.residuals      = gauss3_residuals;
    return problem;
}

