struct enso_model
{
    template <class T> void operator()(const T* b, T* r) const
    {
        using std::cos;
        using std::sin;
        const T pi = T(3.141592653589793238462643383279);
        const double* y = enso_y();
        const double* x_data = enso_x();
        for (int i = 0; i < 168; ++i)
        {
            const T x = T(x_data[i]);
            r[i] = T(y[i]) - (b[0] + b[1]*cos(T(2)*pi*x/T(12)) + b[2]*sin(T(2)*pi*x/T(12)) + b[4]*cos(T(2)*pi*x/b[3]) + b[5]*sin(T(2)*pi*x/b[3]) + b[7]*cos(T(2)*pi*x/b[6]) + b[8]*sin(T(2)*pi*x/b[6]));
        }
    }
};

inline void enso_residuals(const vector_type& b, vector_type& r)
{
    r.resize(168);
    enso_model{}(b.data(), r.data());
}

inline api::least_squares_problem enso_least_squares()
{
    api::least_squares_problem problem;
    problem.num_parameters = 9;
    problem.num_residuals  = 168;
    problem.residuals      = enso_residuals;
    return problem;
}

