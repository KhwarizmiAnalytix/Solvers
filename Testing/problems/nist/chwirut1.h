struct chwirut1_model
{
    template <class T> void operator()(const T* b, T* r) const
    {
        using std::exp;
        const double* y = chwirut1_y();
        const double* x_data = chwirut1_x();
        for (int i = 0; i < 214; ++i)
        {
            const T x = T(x_data[i]);
            r[i] = T(y[i]) - (exp(-b[0]*x) / (b[1] + b[2]*x));
        }
    }
};

inline void chwirut1_residuals(const vector_type& b, vector_type& r)
{
    r.resize(214);
    chwirut1_model{}(b.data(), r.data());
}

inline api::least_squares_problem chwirut1_least_squares()
{
    api::least_squares_problem problem;
    problem.num_parameters = 3;
    problem.num_residuals  = 214;
    problem.residuals      = chwirut1_residuals;
    return problem;
}

